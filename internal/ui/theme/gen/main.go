// Command gen writes the theme package's tokens_gen.go from design/tokens.json and design/layout.json: the spacing
// steps and sizes in steps of Theme.Spacing, the window sizes and radii in DIPs, the opacities, the motion durations,
// the type styles and the layout patterns, so the screens name a token or a layout instead of writing a number. go
// generate runs it in the theme package.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"strconv"
	"strings"
)

// tokens is the part of design/tokens.json that becomes code.
type tokens struct {
	Spacing family `json:"spacing"`
	Size    family `json:"size"`
	Window  family `json:"window"`
	Radius  family `json:"radius"`
	Opacity family `json:"opacity"`
	Motion  family `json:"motion"`
	Type    struct {
		Groups []struct {
			Styles []style `json:"styles"`
		} `json:"groups"`
	} `json:"type"`
}

// style is a type style; its sizes are at the macOS font size, base.
type style struct {
	Name          string  `json:"name"`
	Family        string  `json:"family"`
	FontSize      float64 `json:"fontSize"`
	FontWeight    int     `json:"fontWeight"`
	LineHeight    string  `json:"lineHeight"`
	LetterSpacing string  `json:"letterSpacing"`
	Usage         string  `json:"usage"`
}

// layout is the part of design/layout.json that becomes code.
type layout struct {
	Patterns []pattern `json:"patterns"`
}

// pattern is a layout pattern. Values are token names; padding is CSS style, one, two or four sides.
type pattern struct {
	Name      string   `json:"name"`
	Direction string   `json:"direction"`
	Align     string   `json:"align"`
	Justify   string   `json:"justify"`
	Gap       string   `json:"gap"`
	Padding   []string `json:"padding"`
	Width     string   `json:"width"`
	Height    string   `json:"height"`
	Radius    string   `json:"radius"`
	Usage     string   `json:"usage"`
}

// base is the font size the type styles are drawn at: macOS's 13. A style's size is a multiple of it, so on Windows
// and Linux, at 14, every style scales with the theme.
const base = 13

type family struct {
	Tokens []token `json:"tokens"`
}

type token struct {
	Name  string `json:"name"`
	Value any    `json:"value"`
	Unit  string `json:"unit"`
	Usage string `json:"usage"`
}

func main() {
	if len(os.Args) != 4 {
		fmt.Fprintln(os.Stderr, "usage: gen tokens.json layout.json out.go")
		os.Exit(2)
	}
	src, err := os.ReadFile(os.Args[1])
	var lay []byte
	if err == nil {
		lay, err = os.ReadFile(os.Args[2])
	}
	if err == nil {
		var out []byte
		if out, err = generate(src, lay); err == nil {
			err = os.WriteFile(os.Args[3], out, 0o644)
		}
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
}

// generate turns the tokens and the layout patterns into the Go source of tokens_gen.go.
func generate(src, lay []byte) ([]byte, error) {
	var t tokens
	if err := json.Unmarshal(src, &t); err != nil {
		return nil, err
	}
	var l layout
	if err := json.Unmarshal(lay, &l); err != nil {
		return nil, err
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by go generate from design/tokens.json and design/layout.json; DO NOT EDIT.\n\n" +
		"package theme\n\nimport (\n\t\"time\"\n\n\t\"github.com/egoist/mygo/ui\"\n)\n")
	names := map[string]bool{}
	groups := []struct {
		doc  string
		toks []token
		emit func(token) (string, string, error)
	}{
		{"Spacing steps, in steps of Theme.Spacing: t.Space(Space3). Eight steps and nothing in between.", t.Spacing.Tokens, steps},
		{"Sizes, in steps of Theme.Spacing: t.Space(Control). A sum of tokens is a size too: t.Space(Space3 + BadgeS + Space2).", t.Size.Tokens, steps},
		{"Window sizes, in DIPs.", t.Window.Tokens, dips},
		{"Radii, in DIPs: e.Radius(RadiusCard).", t.Radius.Tokens, dips},
		{"Opacities: e.Opacity(OpacityFaded).", t.Opacity.Tokens, plain},
		{"Durations: c.After(MotionAck).", t.Motion.Tokens, duration},
	}
	for _, g := range groups {
		fmt.Fprintf(&b, "\n// %s\nconst (\n", g.doc)
		for _, tok := range g.toks {
			if tok.Unit != "" {
				continue
			}
			value, at, err := g.emit(tok)
			if err != nil {
				return nil, fmt.Errorf("%s: %w", tok.Name, err)
			}
			fmt.Fprintf(&b, "\t// %s is %s. %s\n\t%s = %s\n", ident(tok.Name), at, tok.Usage, ident(tok.Name), value)
			names[ident(tok.Name)] = true
		}
		b.WriteString(")\n")
	}
	b.WriteString("\n// Type styles: Secondary.On(c, ui.Text(c, s)).\nvar (\n")
	for _, g := range t.Type.Groups {
		for _, st := range g.Styles {
			value, err := typeStyle(st)
			if err != nil {
				return nil, fmt.Errorf("%s: %w", st.Name, err)
			}
			fmt.Fprintf(&b, "\t// %s is %s on %s at the default font size, weight %d. %s\n\t%s = %s\n", ident(st.Name),
				number(st.FontSize), strings.TrimSuffix(st.LineHeight, "px"), st.FontWeight, st.Usage, ident(st.Name), value)
		}
	}
	b.WriteString(")\n")
	for _, p := range l.Patterns {
		if err := layoutFunc(&b, p, names); err != nil {
			return nil, fmt.Errorf("%s: %w", p.Name, err)
		}
	}
	return format.Source(b.Bytes())
}

// layoutFunc writes the function that gives an element a pattern: theme.Inline(c, ui.Row(c)). A pattern with a
// height or a radius is a control's shape, drawn by the control itself, and one with nothing to set (indent,
// spacer, truncate) is a single property the screens write; neither becomes a function. A name a token already has
// takes its direction: bar is BarRow, since Bar is the bar's height.
func layoutFunc(b *bytes.Buffer, p pattern, taken map[string]bool) error {
	if p.Height != "" || p.Radius != "" {
		return nil
	}
	var calls []string
	switch p.Direction {
	case "row":
		calls = append(calls, "Row()")
	case "column":
		calls = append(calls, "Column()")
	case "":
	default:
		return fmt.Errorf("direction %q", p.Direction)
	}
	for _, a := range []struct{ method, value string }{{"AlignItems", p.Align}, {"Justify", p.Justify}} {
		switch a.value {
		case "":
		case "center":
			calls = append(calls, a.method+"(ui.Center)")
		default:
			return fmt.Errorf("%s %q", a.method, a.value)
		}
	}
	if p.Gap != "" {
		calls = append(calls, "Gap("+space(p.Gap)+")")
	}
	if len(p.Padding) > 0 {
		if len(p.Padding) == 3 || len(p.Padding) > 4 {
			return fmt.Errorf("padding %v", p.Padding)
		}
		sides := make([]string, len(p.Padding))
		for i, v := range p.Padding {
			sides[i] = space(v)
		}
		calls = append(calls, "Padding("+strings.Join(sides, ", ")+")")
	}
	switch p.Width {
	case "":
	case "fill":
		calls = append(calls, "FillWidth()")
	default:
		return fmt.Errorf("width %q", p.Width)
	}
	if len(calls) == 0 {
		return nil
	}
	name := ident(p.Name)
	if taken[name] {
		name += ident(p.Direction)
	}
	if taken[name] {
		return fmt.Errorf("%s is a token", name)
	}
	taken[name] = true
	body := "e." + strings.Join(calls, ".")
	if strings.Contains(body, "t.Space") {
		body = "t := c.Theme()\n\treturn " + body
	} else {
		body = "return " + body
	}
	fmt.Fprintf(b, "\n// %s is the %s layout. %s\nfunc %s(c *ui.Context, e ui.Element) ui.Element {\n\t%s\n}\n", name, p.Name, p.Usage, name, body)
	return nil
}

// space is a spacing token in DIPs at the frame's spacing: space-3 is t.Space(Space3); 0 is 0.
func space(name string) string {
	if name == "0" {
		return "0"
	}
	return "t.Space(" + ident(name) + ")"
}

// ident is the Go name of a token: space-0_5 is Space0_5, badge-s is BadgeS.
func ident(name string) string {
	parts := strings.Split(name, "-")
	for i, p := range parts {
		parts[i] = strings.ToUpper(p[:1]) + p[1:]
	}
	return strings.Join(parts, "")
}

// px reads a value such as "28px".
func px(tok token) (float64, error) {
	s, ok := tok.Value.(string)
	if !ok || !strings.HasSuffix(s, "px") {
		return 0, fmt.Errorf("value %v is not in px", tok.Value)
	}
	return strconv.ParseFloat(strings.TrimSuffix(s, "px"), 64)
}

// steps is a px value in steps of the default Theme.Spacing, 4.
func steps(tok token) (string, string, error) {
	v, err := px(tok)
	if err != nil {
		return "", "", err
	}
	return number(v / 4), number(v) + " DIPs at the default spacing", nil
}

func dips(tok token) (string, string, error) {
	v, err := px(tok)
	if err != nil {
		return "", "", err
	}
	return number(v), number(v) + " DIPs", nil
}

func plain(tok token) (string, string, error) {
	v, ok := tok.Value.(float64)
	if !ok {
		return "", "", fmt.Errorf("value %v is not a number", tok.Value)
	}
	return number(v), number(v), nil
}

// duration reads the leading milliseconds of a value such as "200ms ease-out".
func duration(tok token) (string, string, error) {
	s, _ := tok.Value.(string)
	ms, ok := strings.CutSuffix(strings.Fields(s + " ")[0], "ms")
	if !ok {
		return "", "", fmt.Errorf("value %v is not in ms", tok.Value)
	}
	v, err := strconv.Atoi(ms)
	if err != nil {
		return "", "", err
	}
	return fmt.Sprintf("%d * time.Millisecond", v), s, nil
}

// typeStyle is the Style literal of a type style: its size a multiple of base, its line height a multiple of its
// size, its tracking in em.
func typeStyle(st style) (string, error) {
	if st.FontSize <= 0 || st.FontWeight <= 0 {
		return "", fmt.Errorf("size %v, weight %v", st.FontSize, st.FontWeight)
	}
	line, err := strconv.ParseFloat(strings.TrimSuffix(st.LineHeight, "px"), 64)
	if err != nil || !strings.HasSuffix(st.LineHeight, "px") {
		return "", fmt.Errorf("line height %q is not in px", st.LineHeight)
	}
	tracking := 0.0
	if s := st.LetterSpacing; s != "" && s != "0" {
		if tracking, err = strconv.ParseFloat(strings.TrimSuffix(s, "em"), 64); err != nil || !strings.HasSuffix(s, "em") {
			return "", fmt.Errorf("letter spacing %q is not in em", s)
		}
	}
	return fmt.Sprintf("Style{Size: %s, Weight: %d, Line: %s, Tracking: %s, Mono: %t}", ratio(st.FontSize, base), st.FontWeight,
		ratio(line, st.FontSize), number(tracking), st.Family == "mono"), nil
}

// ratio is a/b, rounded to four places.
func ratio(a, b float64) string { return strconv.FormatFloat(a/b, 'f', 4, 64) }

func number(v float64) string { return strconv.FormatFloat(v, 'f', -1, 64) }
