// Command gen writes the theme package's tokens_gen.go from design/tokens.json: the spacing steps and sizes in steps
// of Theme.Spacing, the window sizes and radii in DIPs, the opacities and the motion durations, so the screens name
// a token instead of writing a number. go generate runs it in the theme package.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"strconv"
	"strings"
)

// tokens is the part of design/tokens.json that becomes code.
type tokens struct {
	Spacing family `json:"spacing"`
	Size    family `json:"size"`
	Window  family `json:"window"`
	Radius  family `json:"radius"`
	Opacity family `json:"opacity"`
	Motion  family `json:"motion"`
}

type family struct {
	Tokens []token `json:"tokens"`
}

type token struct {
	Name  string `json:"name"`
	Value any    `json:"value"`
	Unit  string `json:"unit"`
	Usage string `json:"usage"`
}

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: gen tokens.json out.go")
		os.Exit(2)
	}
	src, err := os.ReadFile(os.Args[1])
	if err == nil {
		var out []byte
		if out, err = generate(src); err == nil {
			err = os.WriteFile(os.Args[2], out, 0o644)
		}
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
}

// generate turns the tokens into the Go source of tokens_gen.go.
func generate(src []byte) ([]byte, error) {
	var t tokens
	if err := json.Unmarshal(src, &t); err != nil {
		return nil, err
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by go generate from design/tokens.json; DO NOT EDIT.\n\npackage theme\n\nimport \"time\"\n")
	groups := []struct {
		doc  string
		toks []token
		emit func(token) (string, string, error)
	}{
		{"Spacing steps, in steps of Theme.Spacing: t.Space(Space3). Eight steps and nothing in between.", t.Spacing.Tokens, steps},
		{"Sizes, in steps of Theme.Spacing: t.Space(Control). A sum of tokens is a size too: t.Space(Space3 + BadgeS + Space2).", t.Size.Tokens, steps},
		{"Window sizes, in DIPs.", t.Window.Tokens, dips},
		{"Radii, in DIPs: e.Radius(RadiusCard).", t.Radius.Tokens, dips},
		{"Opacities: e.Opacity(OpacityFaded).", t.Opacity.Tokens, plain},
		{"Durations: c.After(MotionAck).", t.Motion.Tokens, duration},
	}
	for _, g := range groups {
		fmt.Fprintf(&b, "\n// %s\nconst (\n", g.doc)
		for _, tok := range g.toks {
			if tok.Unit != "" {
				continue
			}
			value, at, err := g.emit(tok)
			if err != nil {
				return nil, fmt.Errorf("%s: %w", tok.Name, err)
			}
			fmt.Fprintf(&b, "\t// %s is %s. %s\n\t%s = %s\n", ident(tok.Name), at, tok.Usage, ident(tok.Name), value)
		}
		b.WriteString(")\n")
	}
	return format.Source(b.Bytes())
}

// ident is the Go name of a token: space-0_5 is Space0_5, badge-s is BadgeS.
func ident(name string) string {
	parts := strings.Split(name, "-")
	for i, p := range parts {
		parts[i] = strings.ToUpper(p[:1]) + p[1:]
	}
	return strings.Join(parts, "")
}

// px reads a value such as "28px".
func px(tok token) (float64, error) {
	s, ok := tok.Value.(string)
	if !ok || !strings.HasSuffix(s, "px") {
		return 0, fmt.Errorf("value %v is not in px", tok.Value)
	}
	return strconv.ParseFloat(strings.TrimSuffix(s, "px"), 64)
}

// steps is a px value in steps of the default Theme.Spacing, 4.
func steps(tok token) (string, string, error) {
	v, err := px(tok)
	if err != nil {
		return "", "", err
	}
	return number(v / 4), number(v) + " DIPs at the default spacing", nil
}

func dips(tok token) (string, string, error) {
	v, err := px(tok)
	if err != nil {
		return "", "", err
	}
	return number(v), number(v) + " DIPs", nil
}

func plain(tok token) (string, string, error) {
	v, ok := tok.Value.(float64)
	if !ok {
		return "", "", fmt.Errorf("value %v is not a number", tok.Value)
	}
	return number(v), number(v), nil
}

// duration reads the leading milliseconds of a value such as "200ms ease-out".
func duration(tok token) (string, string, error) {
	s, _ := tok.Value.(string)
	ms, ok := strings.CutSuffix(strings.Fields(s + " ")[0], "ms")
	if !ok {
		return "", "", fmt.Errorf("value %v is not in ms", tok.Value)
	}
	v, err := strconv.Atoi(ms)
	if err != nil {
		return "", "", err
	}
	return fmt.Sprintf("%d * time.Millisecond", v), s, nil
}

func number(v float64) string { return strconv.FormatFloat(v, 'f', -1, 64) }
