package project

import (
	"reflect"
	"strings"
	"testing"
	"time"

	"github.com/yangflow/idset/internal/account"
	"github.com/yangflow/idset/internal/paths"
)

var (
	now  = time.Date(2026, 8, 22, 8, 0, 0, 0, time.UTC)
	unix = paths.Env{Home: "/home/bob"}
)

func fixture() []account.Account {
	return []account.Account{
		{
			ID: "11111111-1111-1111-1111-111111111111", Label: "personal", Provider: account.GitHub, SSHPort: 22,
			SSHAlias: "github-personal", KeyPath: "~/.ssh/id_ed25519", GitUserName: "Alice", GitUserEmail: "alice@example.com",
			Scope: account.Scope{Global: true},
		},
		{
			ID: "22222222-2222-2222-2222-222222222222", Label: "work", Provider: account.GitHub, SSHPort: 443,
			SSHAlias: "github-work", KeyPath: "~/.ssh/id_work", GitUserName: "Bob", GitUserEmail: "bob@example.com",
			Scope: account.Scope{Paths: []string{"~/work/"}},
			URLRewrites: []account.Rewrite{
				{From: "https://github.com/example-org/", To: "git@github-work:example-org/"},
				{From: "git@github.com:example-org/", To: "git@github-work:example-org/"},
			},
		},
	}
}

func TestProjectMatchesTheSpecification(t *testing.T) {
	out := Project(fixture(), unix, now)
	header := "# AUTO-GENERATED BY Idset. Edit in the app or in accounts.json.\n# Last regenerated: 2026-08-22T08:00:00Z\n\n"
	wantSSH := header + `Host github-personal
	HostName github.com
	Port 22
	User git
	IdentityFile "~/.ssh/id_ed25519"
	IdentitiesOnly yes

Host github-work
	HostName ssh.github.com
	Port 443
	User git
	IdentityFile "~/.ssh/id_work"
	IdentitiesOnly yes
	HostKeyAlias github.com

`
	if out.SSH != wantSSH {
		t.Errorf("ssh:\n%s", out.SSH)
	}
	wantGit := header + `[user]
	name = Alice
	email = alice@example.com

[url "git@github-work:example-org/"]
	insteadOf = https://github.com/example-org/
	insteadOf = git@github.com:example-org/

[includeIf "gitdir:~/work/"]
	path = ~/.config/idset/gitconfig-22222222-2222-2222-2222-222222222222.managed

`
	if out.Git != wantGit {
		t.Errorf("git:\n%s", out.Git)
	}
	wantSub := `# AUTO-GENERATED BY Idset for account 22222222-2222-2222-2222-222222222222 (work)

[user]
	name = Bob
	email = bob@example.com

[core]
	sshCommand = ssh -i \"/home/bob/.ssh/id_work\" -o IdentitiesOnly=yes
`
	if len(out.Subs) != 1 || out.Subs[SubFile("22222222-2222-2222-2222-222222222222")] != wantSub {
		t.Errorf("subs: %#v", out.Subs)
	}
}

func TestProjectIsDeterministic(t *testing.T) {
	if a, b := Project(fixture(), unix, now), Project(fixture(), unix, now); !reflect.DeepEqual(a, b) {
		t.Fatal("same input, different output")
	}
}

func TestHostsAreSkippedWithoutAliasOrKey(t *testing.T) {
	list := fixture()
	list[0].SSHAlias = ""
	list[1].KeyPath = ""
	out := Project(list, unix, now)
	if strings.Contains(out.SSH, "Host ") {
		t.Errorf("ssh:\n%s", out.SSH)
	}
	if strings.Contains(out.Subs[SubFile(list[1].ID)], "[core]") {
		t.Error("no key, no sshCommand")
	}
}

func TestOtherProviders(t *testing.T) {
	list := []account.Account{
		{ID: "a", SSHAlias: "gl", KeyPath: "~/k", Provider: account.GitLab, SSHPort: 443},
		{ID: "b", SSHAlias: "corp", KeyPath: "~/k2", Provider: account.Custom, HostName: "git.example.com", SSHPort: 2222},
	}
	out := Project(list, unix, now).SSH
	for _, want := range []string{
		"Host gl\n\tHostName altssh.gitlab.com\n\tPort 443\n",
		"\tHostKeyAlias gitlab.com\n",
		"Host corp\n\tHostName git.example.com\n\tPort 2222\n\tUser git\n\tIdentityFile \"~/k2\"\n\tIdentitiesOnly yes\n\n",
	} {
		if !strings.Contains(out, want) {
			t.Errorf("missing %q in:\n%s", want, out)
		}
	}
}

func TestLastGlobalWins(t *testing.T) {
	list := fixture()
	second := list[0]
	second.ID, second.GitUserName, second.GitUserEmail = "33333333-3333-3333-3333-333333333333", "Carol", "carol@example.com"
	unnamed := second
	unnamed.ID, unnamed.GitUserName, unnamed.GitUserEmail = "44444444-4444-4444-4444-444444444444", "", ""
	git := Project(append(list, second, unnamed), unix, now).Git
	if !strings.Contains(git, "name = Carol") || strings.Contains(git, "name = Alice") {
		t.Errorf("git:\n%s", git)
	}
}

func TestRewritesAreGroupedSortedAndDeduplicated(t *testing.T) {
	list := []account.Account{
		{ID: "a", URLRewrites: []account.Rewrite{
			{From: "https://x/", To: "git@z:"},
			{From: "https://x/", To: "git@z:"},
			{From: "", To: "git@z:"},
			{From: "https://p/", To: "git@z:", Push: true},
		}},
		{ID: "b", Scope: account.Scope{Paths: []string{"~/b/"}}, URLRewrites: []account.Rewrite{{From: "https://y/", To: "git@a:"}, {From: "https://w/", To: "git@z:"}}},
	}
	git := Project(list, unix, now).Git
	want := `[url "git@a:"]
	insteadOf = https://y/

[url "git@z:"]
	insteadOf = https://x/
	pushInsteadOf = https://p/
	insteadOf = https://w/

`
	if !strings.Contains(git, want) {
		t.Errorf("git:\n%s", git)
	}
}

func TestValuesAreEscaped(t *testing.T) {
	list := fixture()
	list[0].GitUserName = `Ann "#1" O\Neil`
	list[0].GitUserEmail = " ann@example.com"
	git := Project(list, unix, now).Git
	for _, want := range []string{`name = "Ann \"#1\" O\\Neil"`, `email = " ann@example.com"`} {
		if !strings.Contains(git, want) {
			t.Errorf("missing %s in:\n%s", want, git)
		}
	}
}

func TestWindows(t *testing.T) {
	win := paths.Env{Home: `C:\Users\Bob`, Windows: true}
	list := fixture()
	list[1].Scope.Paths = []string{`C:\Users\Bob\Work`, `D:\src`}
	list[1].KeyPath = `C:\Users\Bob\.ssh\id_work`
	out := Project(list, win, now)
	for _, want := range []string{`[includeIf "gitdir/i:~/Work/"]`, `[includeIf "gitdir/i:D:/src/"]`} {
		if !strings.Contains(out.Git, want) {
			t.Errorf("missing %s in:\n%s", want, out.Git)
		}
	}
	if !strings.Contains(out.SSH, `IdentityFile "C:/Users/Bob/.ssh/id_work"`) {
		t.Errorf("ssh:\n%s", out.SSH)
	}
	if !strings.Contains(out.Subs[SubFile(list[1].ID)], `ssh -i \"C:/Users/Bob/.ssh/id_work\"`) {
		t.Errorf("sub:\n%s", out.Subs[SubFile(list[1].ID)])
	}
}

func TestSubFilesOnlyForUsablePaths(t *testing.T) {
	list := fixture()
	list[1].Scope.Paths = []string{" ", ""}
	out := Project(list, unix, now)
	if len(out.Subs) != 0 || strings.Contains(out.Git, "includeIf") {
		t.Errorf("blank paths produced output: %#v", out.Subs)
	}
}
