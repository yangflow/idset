// Package project turns the identity list into the contents of the managed files. It is pure: the same list,
// environment and time always give the same output, and nothing here touches the disk.
package project

import (
	"fmt"
	"slices"
	"strings"
	"time"

	"github.com/yangflow/idset/internal/account"
	"github.com/yangflow/idset/internal/gitdir"
	"github.com/yangflow/idset/internal/paths"
)

// Dir is the Idset directory in the form written into Include and includeIf, expanded by ssh and git.
const Dir = "~/.config/idset"

const (
	SSHFile = "ssh_config.managed"
	GitFile = "gitconfig.managed"
)

// SubFile is the name of the per-identity gitconfig that a gitdir includeIf points at.
func SubFile(id string) string { return "gitconfig-" + id + ".managed" }

// Output is the content of every managed file; Subs maps a SubFile name to its content.
type Output struct {
	SSH  string
	Git  string
	Subs map[string]string
}

// Project generates the managed files for list.
func Project(list []account.Account, env paths.Env, now time.Time) Output {
	header := "# AUTO-GENERATED BY Idset. Edit in the app or in accounts.json.\n" +
		"# Last regenerated: " + now.UTC().Format(time.RFC3339) + "\n\n"
	out := Output{SSH: header + sshHosts(list), Git: header + gitMain(list, env), Subs: map[string]string{}}
	for _, b := range gitdir.Blocks(list, env) {
		a := list[b.Index]
		if name := SubFile(a.ID); out.Subs[name] == "" {
			out.Subs[name] = sub(a, env)
		}
	}
	return out
}

func sshHosts(list []account.Account) string {
	var b strings.Builder
	for _, a := range list {
		if a.SSHAlias == "" || a.KeyPath == "" {
			continue
		}
		fmt.Fprintf(&b, "Host %s\n\tHostName %s\n\tPort %d\n\tUser git\n\tIdentityFile \"%s\"\n\tIdentitiesOnly yes\n",
			a.SSHAlias, a.RealHost(), a.SSHPort, paths.Slash(a.KeyPath))
		if alias := a.HostKeyAlias(); alias != "" {
			fmt.Fprintf(&b, "\tHostKeyAlias %s\n", alias)
		}
		b.WriteString("\n")
	}
	return b.String()
}

func gitMain(list []account.Account, env paths.Env) string {
	var b strings.Builder
	// git keeps the last [user] it reads, so with several global identities (only possible by editing the file)
	// the last one in storage order is the one in effect.
	for i := len(list) - 1; i >= 0; i-- {
		if a := list[i]; a.Scope.Global && (a.GitUserName != "" || a.GitUserEmail != "") {
			b.WriteString(user(a))
			break
		}
	}
	b.WriteString(rewrites(list))
	for _, blk := range gitdir.Blocks(list, env) {
		fmt.Fprintf(&b, "[includeIf %s]\n\tpath = %s/%s\n\n",
			quoteSubsection(gitdir.Keyword(env)+blk.Path), Dir, SubFile(list[blk.Index].ID))
	}
	return b.String()
}

func user(a account.Account) string {
	var b strings.Builder
	b.WriteString("[user]\n")
	if a.GitUserName != "" {
		fmt.Fprintf(&b, "\tname = %s\n", value(a.GitUserName))
	}
	if a.GitUserEmail != "" {
		fmt.Fprintf(&b, "\temail = %s\n", value(a.GitUserEmail))
	}
	return b.String() + "\n"
}

func rewrites(list []account.Account) string {
	type group struct {
		to    string
		rules []account.Rewrite
	}
	var groups []*group
	byTo := map[string]*group{}
	seen := map[account.Rewrite]bool{}
	for _, a := range list {
		for _, r := range a.URLRewrites {
			if r.From == "" || r.To == "" || seen[r] {
				continue
			}
			seen[r] = true
			g := byTo[r.To]
			if g == nil {
				g = &group{to: r.To}
				byTo[r.To] = g
				groups = append(groups, g)
			}
			g.rules = append(g.rules, r)
		}
	}
	slices.SortStableFunc(groups, func(a, b *group) int { return strings.Compare(a.to, b.to) })
	var b strings.Builder
	for _, g := range groups {
		fmt.Fprintf(&b, "[url %s]\n", quoteSubsection(g.to))
		for _, r := range g.rules {
			key := "insteadOf"
			if r.Push {
				key = "pushInsteadOf"
			}
			fmt.Fprintf(&b, "\t%s = %s\n", key, value(r.From))
		}
		b.WriteString("\n")
	}
	return b.String()
}

func sub(a account.Account, env paths.Env) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# AUTO-GENERATED BY Idset for account %s (%s)\n\n", a.ID, a.Label)
	if a.GitUserName != "" || a.GitUserEmail != "" {
		b.WriteString(user(a))
	}
	if a.KeyPath != "" {
		// sshCommand goes through a shell, which does not expand ~ inside quotes, so the path is absolute.
		cmd := `ssh -i "` + env.Expand(a.KeyPath) + `" -o IdentitiesOnly=yes`
		fmt.Fprintf(&b, "[core]\n\tsshCommand = %s\n", value(cmd))
	}
	return strings.TrimRight(b.String(), "\n") + "\n"
}

// value escapes a gitconfig value, quoting it when it would otherwise lose a comment character or spaces.
func value(v string) string {
	escaped := strings.NewReplacer(`\`, `\\`, `"`, `\"`, "\t", `\t`).Replace(v)
	if strings.ContainsAny(v, "#;") || strings.TrimSpace(v) != v {
		return `"` + escaped + `"`
	}
	return escaped
}

func quoteSubsection(s string) string {
	return `"` + strings.NewReplacer(`\`, `\\`, `"`, `\"`).Replace(s) + `"`
}
